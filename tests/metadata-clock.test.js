const assert = require('node:assert/strict');
const Clock = require('../assets/net-fm-metadata-clock.js');
const shown = [], prepared = [];
const clock = new Clock(x => shown.push(x), x => prepared.push(x), 0.5);
clock.enqueue(4, 'Jingle');
clock.enqueue(6, 'Song');
clock.advance(3.7, false);
assert.deepEqual(prepared, [], 'Paused audio must not prepare a transition');
clock.advance(3.7, true);
clock.advance(3.9, true);
assert.deepEqual(prepared, ['Jingle'], 'Preparation must run once');
clock.advance(4, true);
assert.deepEqual(shown, ['Jingle']);
clock.advance(5, false);
clock.clear();
clock.advance(7, true);
assert.deepEqual(shown, ['Jingle'], 'Clearing on station change must cancel old metadata');
assert.throws(() => clock.enqueue(NaN, 'bad'), TypeError);
console.log('Timed metadata respects playback, preparation and cancellation');
